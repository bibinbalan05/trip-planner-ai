// Runs automatically before `npm run build` (npm "prebuild" hook).
//
// Angular bakes configuration in at build time, so the production backend URL has to be
// known when the app is built. On Render, set the API_BASE_URL environment variable on the
// static site; this script writes it into src/environments/environment.production.ts.
// If API_BASE_URL is not set, the committed file is left untouched.

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const raw = process.env.API_BASE_URL?.trim();

if (!raw) {
  console.log('[set-api-url] API_BASE_URL not set; keeping src/environments/environment.production.ts as is.');
  process.exit(0);
}

let url;
try {
  url = new URL(raw);
} catch {
  console.error(`[set-api-url] API_BASE_URL is not a valid URL: "${raw}"`);
  process.exit(1);
}

if (url.protocol !== 'https:' && url.protocol !== 'http:') {
  console.error('[set-api-url] API_BASE_URL must start with http:// or https://');
  process.exit(1);
}

const apiBaseUrl = url.origin + url.pathname.replace(/\/+$/, '');
const target = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/environments/environment.production.ts',
);

const contents = `// Generated by scripts/set-api-url.mjs from the API_BASE_URL environment variable.
export const environment = {
  production: true,
  apiBaseUrl: ${JSON.stringify(apiBaseUrl)},
};
`;

writeFileSync(target, contents, 'utf8');
console.log(`[set-api-url] Production API base URL set to ${apiBaseUrl}`);
